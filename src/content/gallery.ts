export const gallerySequence = chapters.flatMap((chapter) =>
  chapter.layout === "hero-rows"
    ? [chapter.hero, ...(chapter.rows ?? []).flat()]
    : [chapter.lead, ...(chapter.stack ?? [])],
) as PlateKey[];

export const plateNumbers = new Map<PlateKey, string>(
  gallerySequence.map((key, index) => [key, String(index + 1).padStart(2, "0")]),
);

export const chapterCount = (chapter: Chapter) =>
  chapter.layout === "hero-rows"
    ? 1 + (chapter.rows ?? []).reduce((total, row) => total + row.length, 0)
    : 1 + (chapter.stack?.length ?? 0);
